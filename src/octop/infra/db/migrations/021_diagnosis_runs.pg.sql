-- Schema v21: store-diagnosis runs, items, and node events.

CREATE TABLE IF NOT EXISTS diag_runs (
  id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id             TEXT NOT NULL UNIQUE,
  owner_user_id      INTEGER NOT NULL REFERENCES users(id),
  client_request_id  TEXT NOT NULL UNIQUE,
  status             TEXT NOT NULL DEFAULT 'PREPARING',
  report_ref         TEXT
);

CREATE TABLE IF NOT EXISTS diag_run_items (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id    TEXT NOT NULL UNIQUE,
  run_id     TEXT NOT NULL REFERENCES diag_runs(run_id),
  store_id   TEXT NOT NULL,
  attempt    INTEGER NOT NULL,
  status     TEXT NOT NULL,
  slice_ref  TEXT,
  UNIQUE (run_id, store_id, attempt)
);

CREATE TABLE IF NOT EXISTS diag_node_events (
  id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id   TEXT NOT NULL REFERENCES diag_runs(run_id),
  item_id  TEXT,
  node     TEXT NOT NULL,
  event    TEXT NOT NULL,
  detail   TEXT,
  ts       INTEGER NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_diag_node_events_run_id
  ON diag_node_events(run_id);

UPDATE _schema_version SET version = 21;
